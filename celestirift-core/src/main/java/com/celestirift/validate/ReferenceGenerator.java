package com.celestirift.validate;

import com.celestirift.CelestiRift;
import com.celestirift.api.skill.ConfigMap;
import com.celestirift.skill.registry.ComponentRegistry;
import com.google.gson.GsonBuilder;
import com.google.gson.JsonArray;
import com.google.gson.JsonObject;
import com.google.gson.JsonPrimitive;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Map;

/**
 * Generates authoring aids from the live registries (so add-on mechanics are included):
 * <ul>
 *   <li>{@code schema/skills.schema.json} — JSON Schema for editor autocomplete/hover.
 *       In VS Code (Red Hat YAML extension) put this at the top of a skill file:
 *       {@code # yaml-language-server: $schema=../schema/skills.schema.json}</li>
 *   <li>{@code docs/reference.md} — every mechanic/targeter/condition with its attributes.</li>
 * </ul>
 */
public final class ReferenceGenerator {

    private final CelestiRift plugin;

    public ReferenceGenerator(CelestiRift plugin) {
        this.plugin = plugin;
    }

    public void writeAll() {
        Path root = plugin.getDataFolder().toPath();
        try {
            write(root.resolve("schema/skills.schema.json"),
                    new GsonBuilder().setPrettyPrinting().disableHtmlEscaping().create().toJson(schema()));
            write(root.resolve("docs/reference.md"), markdown());
        } catch (IOException | RuntimeException e) {
            plugin.getLogger().warning("Could not write schema/docs: " + e.getMessage());
        }
    }

    private static void write(Path file, String content) throws IOException {
        Files.createDirectories(file.getParent());
        Files.writeString(file, content, StandardCharsets.UTF_8);
    }

    // ------------------------------------------------------------------ JSON schema

    public JsonObject schema() {
        var skills = plugin.skills();
        JsonObject root = new JsonObject();
        root.addProperty("$schema", "http://json-schema.org/draft-07/schema#");
        root.addProperty("title", "CelestiRift skills");
        root.addProperty("description", "Generated by CelestiRift from the installed mechanics. Do not edit.");
        root.addProperty("type", "object");
        root.add("additionalProperties", ref("skill"));

        JsonObject defs = new JsonObject();
        defs.add("skill", skillDef());
        defs.add("line", lineDef(defs, skills.mechanics()));
        defs.add("target", componentRef(defs, "targeter", skills.targeters(),
                "Targeter: a name like \"self\" / \"@target{range=10}\", "
                + "or a one-key map like { nearby: { radius: 4 } }."));
        defs.add("condition", componentRef(defs, "condition", skills.conditions(),
                "Condition: a string like \"health{value=>10}\" "
                + "(prefix ! to negate) or a one-key map like { health: \">10\" } / { not: { ... } }."));
        defs.add("conditions", anyOf(ref("condition"), arrayOf(ref("condition"))));
        root.add("definitions", defs);
        return root;
    }

    private JsonObject skillDef() {
        JsonObject props = new JsonObject();
        prop(props, "cooldown", type("number", "Cooldown in seconds (player casts)."));
        prop(props, "mana", type("number", "Mana cost (player casts)."));
        prop(props, "description", type("string", "MiniMessage description shown in menus and /cr info."));
        prop(props, "extends", type("string", "Inherit every unset key from another skill."));
        JsonObject vars = type("object", "Variables usable as ${name} in any line. Children override parents.");
        props.add("variables", vars);
        props.add("Variables", vars);
        prop(props, "conditions", withDesc(arrayOf(ref("condition")),
                "Skill-level conditions: if one fails the skill doesn't cast and nothing is spent."));
        prop(props, "skills", withDesc(arrayOf(ref("line")),
                "Lines run top to bottom. A string 'mechanic{attrs} @targeter ?condition' or a map."));
        JsonObject item = type("object", "Skill item look (/cr give).");
        JsonObject itemProps = new JsonObject();
        itemProps.add("model", type("string", "Item model from a resource pack, e.g. celestirift:fireball."));
        itemProps.add("name-gradient", gradient());
        itemProps.add("mana-gradient", gradient());
        item.add("properties", itemProps);
        prop(props, "item", item);

        JsonObject skill = new JsonObject();
        skill.addProperty("type", "object");
        skill.add("properties", props);
        return skill;
    }

    private static JsonObject gradient() {
        JsonObject g = type("object", "MiniMessage gradient endpoints.");
        JsonObject p = new JsonObject();
        p.add("from", type("string", "#RRGGBB"));
        p.add("to", type("string", "#RRGGBB"));
        g.add("properties", p);
        return g;
    }

    /** Adds {@code key} and its Capitalised spelling (keys are case-insensitive). */
    private static void prop(JsonObject props, String key, JsonObject value) {
        props.add(key, value);
        props.add(Character.toUpperCase(key.charAt(0)) + key.substring(1), value);
    }

    private JsonObject lineDef(JsonObject defs, ComponentRegistry<?> mechanics) {
        JsonObject structured = new JsonObject();
        structured.addProperty("type", "object");
        structured.addProperty("minProperties", 1);
        JsonObject props = new JsonObject();
        props.add("target", withDesc(ref("target"), "Who/where the mechanic acts on (default: self)."));
        props.add("if", withDesc(ref("conditions"), "Conditions for this line; all must pass."));
        props.add("chance", withDesc(range(0, 1), "Probability (0-1) that the line runs."));
        props.add("trigger", type("string", "Optional trigger tag."));
        for (var d : mechanics.describe().values()) {
            String def = "mechanic." + d.name();
            defs.add(def, componentValue(d, "Mechanic"));
            props.add(d.name(), ref(def));
            for (String alias : d.aliases()) {
                props.add(alias, ref(def));
            }
        }
        structured.add("properties", props);

        JsonObject str = type("string", "mechanic{attr=value;...} @targeter{...} ?condition{...}");
        return anyOf(str, structured);
    }

    /** A targeter/condition reference: string, or one-key map of any registered component. */
    private JsonObject componentRef(JsonObject defs, String kind, ComponentRegistry<?> registry, String description) {
        JsonObject map = new JsonObject();
        map.addProperty("type", "object");
        map.addProperty("minProperties", 1);
        map.addProperty("maxProperties", 1);
        JsonObject props = new JsonObject();
        for (var d : registry.describe().values()) {
            String def = kind + "." + d.name();
            defs.add(def, componentValue(d, ""));
            props.add(d.name(), ref(def));
            for (String alias : d.aliases()) {
                props.add(alias, ref(def));
            }
        }
        props.add("not", type("object", "Negate the condition inside."));
        map.add("properties", props);

        JsonObject str = new JsonObject();
        str.addProperty("type", "string");
        JsonArray examples = new JsonArray();
        registry.describe().keySet().forEach(examples::add);
        str.add("examples", examples);
        return withDesc(anyOf(str, map), description);
    }

    /** A component's value: attribute map, shorthand scalar for the primary attribute, or null. */
    private static JsonObject componentValue(ComponentRegistry.Description d, String kind) {
        JsonObject attrs = new JsonObject();
        attrs.addProperty("type", "object");
        JsonObject props = new JsonObject();
        for (ConfigMap.Attribute a : d.attributes()) {
            JsonObject p = attributeSchema(a);
            props.add(a.name(), p);
        }
        props.add("chance", withDesc(range(0, 1), "Probability (0-1) that the line runs."));
        attrs.add("properties", props);

        JsonArray any = new JsonArray();
        any.add(attrs);
        if (d.primary() != null) {
            ConfigMap.Attribute primary = d.attributes().getFirst();
            any.add(withDesc(attributeSchema(primary), "Shorthand for " + primary.name() + "."));
        }
        JsonObject nul = new JsonObject();
        nul.addProperty("type", "null");
        any.add(nul);

        JsonObject out = new JsonObject();
        out.add("anyOf", any);
        out.addProperty("description", (kind.isEmpty() ? "" : kind + " ") + d.name()
                + (d.aliases().isEmpty() ? "" : " (aliases: " + String.join(", ", d.aliases()) + ")")
                + attributeSummary(d.attributes()));
        return out;
    }

    private static JsonObject attributeSchema(ConfigMap.Attribute a) {
        JsonObject p = new JsonObject();
        JsonArray types = new JsonArray();
        switch (a.type()) {
            case INT -> types.add("integer");
            case DOUBLE, NUMBER -> types.add("number");
            case BOOLEAN -> types.add("boolean");
            default -> types.add("string");
        }
        types.add("string"); // allow ${variables} and expressions
        p.add("type", types);
        if (a.defaultValue() != null) {
            p.add("default", primitive(a.defaultValue()));
        }
        p.addProperty("description", "default: " + a.defaultValue()
                + (a.aliases().isEmpty() ? "" : " · aliases: " + String.join(", ", a.aliases())));
        return p;
    }

    private static String attributeSummary(List<ConfigMap.Attribute> attrs) {
        if (attrs.isEmpty()) {
            return "";
        }
        StringBuilder sb = new StringBuilder("\nAttributes:");
        for (ConfigMap.Attribute a : attrs) {
            sb.append("\n • ").append(a.name()).append(" (").append(a.type().name().toLowerCase())
                    .append(", default ").append(a.defaultValue()).append(')');
        }
        return sb.toString();
    }

    private static JsonPrimitive primitive(Object v) {
        if (v instanceof Number n) return new JsonPrimitive(n);
        if (v instanceof Boolean b) return new JsonPrimitive(b);
        return new JsonPrimitive(String.valueOf(v));
    }

    private static JsonObject ref(String def) {
        JsonObject o = new JsonObject();
        o.addProperty("$ref", "#/definitions/" + def);
        return o;
    }

    private static JsonObject type(String type, String description) {
        JsonObject o = new JsonObject();
        o.addProperty("type", type);
        o.addProperty("description", description);
        return o;
    }

    private static JsonObject range(double min, double max) {
        JsonObject o = new JsonObject();
        o.addProperty("type", "number");
        o.addProperty("minimum", min);
        o.addProperty("maximum", max);
        return o;
    }

    private static JsonObject arrayOf(JsonObject items) {
        JsonObject o = new JsonObject();
        o.addProperty("type", "array");
        o.add("items", items);
        return o;
    }

    private static JsonObject anyOf(JsonObject a, JsonObject b) {
        JsonObject o = new JsonObject();
        JsonArray arr = new JsonArray();
        arr.add(a);
        arr.add(b);
        o.add("anyOf", arr);
        return o;
    }

    private static JsonObject withDesc(JsonObject o, String description) {
        o.addProperty("description", description);
        return o;
    }

    // ------------------------------------------------------------------ markdown

    public String markdown() {
        var skills = plugin.skills();
        StringBuilder sb = new StringBuilder();
        sb.append("# CelestiRift reference\n\n")
                .append("_Generated from the installed mechanics on every `/cr reload`. Do not edit._\n\n")
                .append("The **first attribute** of each component is its *shorthand*: `- delay: 20` means "
                        + "`delay{ticks=20}`.\n\n");
        section(sb, "Mechanics", skills.mechanics().describe());
        section(sb, "Targeters", skills.targeters().describe());
        section(sb, "Conditions", skills.conditions().describe());
        return sb.toString();
    }

    private static void section(StringBuilder sb, String title, Map<String, ComponentRegistry.Description> map) {
        sb.append("## ").append(title).append("\n\n");
        for (var d : map.values()) {
            sb.append("### `").append(d.name()).append("`");
            if (!d.aliases().isEmpty()) {
                sb.append(" — aliases: ").append(String.join(", ", d.aliases().stream().map(a -> "`" + a + "`").toList()));
            }
            sb.append("\n\n");
            if (d.attributes().isEmpty()) {
                sb.append("_No attributes._\n\n");
                continue;
            }
            sb.append("| Attribute | Aliases | Type | Default |\n|---|---|---|---|\n");
            boolean first = true;
            for (ConfigMap.Attribute a : d.attributes()) {
                sb.append("| `").append(a.name()).append('`').append(first ? " *(shorthand)*" : "")
                        .append(" | ").append(String.join(", ", a.aliases()))
                        .append(" | ").append(a.type().name().toLowerCase())
                        .append(" | ").append(a.defaultValue() == null ? "" : "`" + a.defaultValue() + "`")
                        .append(" |\n");
                first = false;
            }
            sb.append('\n');
        }
    }
}
